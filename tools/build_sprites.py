#!/usr/bin/env python3
"""Rasterise the extracted sprite SVGs and generate the sprite metadata table.

The renderers load plain RGBA PNGs by file name, so the only thing the shared
library needs to know about the art is each sprite's aspect ratio: it uses that
to emit undistorted quads at whatever world size the design calls for.

Outputs
  assets/dist/<name>.png            the textures every platform bundles
  core/src/generated/sprites.rs     file names + aspect ratios

Requires rsvg-convert and ImageMagick.  Run via tools/build_assets.sh.
"""

import os
import subprocess
import sys

MAGICK = os.environ.get("MAGICK", "magick")
RSVG = os.environ.get("RSVG", "rsvg-convert")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SPRITES = os.path.join(ROOT, "assets", "sprites")
DIST = os.path.join(ROOT, "assets", "dist")
GEN_RS = os.path.join(ROOT, "core", "src", "generated", "sprites.rs")

# Must stay in sync with gc_sprite_id in include/game_core.h.
SPRITE_NAMES = ["player", "enemy_a", "enemy_b", "gun", "bow", "sword",
                "money", "xp"]

RASTER_WIDTH = 512  # plenty for a 720-unit design height, even on 3x displays


def run(args):
    proc = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True)
    if proc.returncode != 0:
        raise SystemExit("command failed: %s\n%s" % (" ".join(args), proc.stdout))
    return proc.stdout


def rasterise(name):
    svg = os.path.join(SPRITES, name + ".svg")
    if not os.path.exists(svg):
        raise SystemExit("missing %s -- run tools/extract_sprites.py first" % svg)
    tmp = os.path.join(DIST, "." + name + ".raw.png")
    out = os.path.join(DIST, name + ".png")
    run([RSVG, "-w", str(RASTER_WIDTH), svg, "-o", tmp])
    # Trim the transparent padding so the quad the library emits is exactly the
    # art: the aspect ratio then means something.
    run([MAGICK, tmp, "-background", "none", "-trim", "+repage",
         "PNG32:" + out])
    os.remove(tmp)
    info = run([MAGICK, "identify", "-format", "%w %h", out]).split()
    return int(info[0]), int(info[1])


def main():
    os.makedirs(DIST, exist_ok=True)
    sizes = []
    for name in SPRITE_NAMES:
        w, h = rasterise(name)
        sizes.append((name, w, h))
        print("%-8s %4dx%-4d -> assets/dist/%s.png" % (name, w, h, name))

    files = ", ".join('"%s.png"' % n for n, _, _ in sizes)
    aspects = ", ".join("%.6f" % (w / h) for _, w, h in sizes)
    pixels = ", ".join("(%d, %d)" % (w, h) for _, w, h in sizes)

    os.makedirs(os.path.dirname(GEN_RS), exist_ok=True)
    with open(GEN_RS, "w", encoding="utf-8") as fh:
        fh.write(f"""// @generated by tools/build_sprites.py -- DO NOT EDIT BY HAND.
#![allow(dead_code)]
//
// Sprite table for the textures in assets/dist/.  Index order matches
// gc_sprite_id in include/game_core.h.

use crate::sprite::SpriteId;

/// Texture file name for each sprite, indexed by SpriteId.
pub const SPRITE_FILES: [&str; {len(sizes)}] = [{files}];

/// Source texture size in pixels (informational).
pub const SPRITE_PIXELS: [(u32, u32); {len(sizes)}] = [{pixels}];

/// width / height of each trimmed texture, so quads are never distorted.
pub const SPRITE_ASPECT: [f32; {len(sizes)}] = [{aspects}];

/// Convenience accessor.
pub fn aspect_of(id: SpriteId) -> f32 {{
    SPRITE_ASPECT[id as usize]
}}

/// Convenience accessor.
pub fn file_of(id: SpriteId) -> &'static str {{
    SPRITE_FILES[id as usize]
}}
""")
    print("metadata -> %s" % os.path.relpath(GEN_RS, ROOT))


if __name__ == "__main__":
    main()
